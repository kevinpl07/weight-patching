"""Prepare pretraining data: train a small byte-level BPE tokenizer and write uint16 token streams.

Datasets:
  tinystories  roneneldan/TinyStories (full)                         -> pretrain/data/
  fineweb      HuggingFaceFW/fineweb-edu, sample-10BT, streamed;     -> pretrain/data_fw/
  code         codeparrot/codeparrot-clean (Python), streamed;       -> pretrain/data_code/
               the first --val-docs documents are the val split, the next --docs are train.

Output: tokenizer.json, train.bin, val.bin (documents joined with <|eos|> = id 0), meta.json

Usage:
  .venv/Scripts/python.exe pretrain/data.py --dataset tinystories --vocab 4096
  .venv/Scripts/python.exe pretrain/data.py --dataset fineweb --vocab 8192 --docs 500000
"""
import argparse
import itertools
import json
import os
import time

import numpy as np
from datasets import load_dataset
from tokenizers import Tokenizer, decoders, models, pre_tokenizers, trainers

HERE = os.path.dirname(os.path.abspath(__file__))
EOS = "<|eos|>"


def train_tokenizer(texts, vocab):
    tok = Tokenizer(models.BPE())
    tok.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
    tok.decoder = decoders.ByteLevel()
    trainer = trainers.BpeTrainer(vocab_size=vocab, special_tokens=[EOS],
                                  initial_alphabet=pre_tokenizers.ByteLevel.alphabet(), min_frequency=2)
    tok.train_from_iterator(texts, trainer=trainer, length=len(texts))
    assert tok.token_to_id(EOS) == 0
    return tok


def write_split(tok, text_iter, path, t0, name, batch=5000):
    n_tok = n_doc = 0
    with open(path, "wb") as f:
        while True:
            chunk = list(itertools.islice(text_iter, batch))
            if not chunk:
                break
            for e in tok.encode_batch([t.strip() for t in chunk]):
                np.asarray(e.ids + [0], dtype=np.uint16).tofile(f)
                n_tok += len(e.ids) + 1
            n_doc += len(chunk)
            if (n_doc // batch) % 10 == 0:
                print(f"  {name}: {n_doc:,} docs, {n_tok/1e6:.1f}M tokens  {time.time()-t0:.0f}s", flush=True)
    print(f"{name}: {n_doc:,} docs, {n_tok:,} tokens", flush=True)
    return n_tok, n_doc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", choices=["tinystories", "fineweb", "code"], default="tinystories")
    ap.add_argument("--vocab", type=int, default=None)
    ap.add_argument("--tok-docs", type=int, default=None, help="documents used to train the tokenizer")
    ap.add_argument("--docs", type=int, default=500_000, help="fineweb: train documents")
    ap.add_argument("--val-docs", type=int, default=10_000, help="fineweb: val documents")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    t0 = time.time()

    if a.dataset == "tinystories":
        out = a.out or os.path.join(HERE, "data")
        vocab, tok_docs = a.vocab or 4096, a.tok_docs or 300_000
        ds = load_dataset("roneneldan/TinyStories")
        tok = train_tokenizer(ds["train"].select(range(tok_docs))["text"], vocab)
        val_iter, train_iter = iter(ds["validation"]["text"]), iter(ds["train"]["text"])
    else:
        if a.dataset == "fineweb":
            out = a.out or os.path.join(HERE, "data_fw")
            vocab, tok_docs = a.vocab or 8192, a.tok_docs or 100_000
            stream = load_dataset("HuggingFaceFW/fineweb-edu", name="sample-10BT", split="train", streaming=True)
            texts = (r["text"] for r in stream)
        else:  # code: Python files, skipping autogenerated files and very large ones (data tables)
            out = a.out or os.path.join(HERE, "data_code")
            vocab, tok_docs = a.vocab or 8192, a.tok_docs or 50_000
            stream = load_dataset("codeparrot/codeparrot-clean", split="train", streaming=True)
            texts = (r["content"] for r in stream if not r["autogenerated"] and len(r["content"]) <= 50_000)
        val_texts = list(itertools.islice(texts, a.val_docs))
        head = list(itertools.islice(texts, tok_docs))  # tokenizer docs are also the start of train
        print(f"streamed {len(val_texts)+len(head):,} docs for val + tokenizer in {time.time()-t0:.0f}s", flush=True)
        tok = train_tokenizer(head, vocab)
        val_iter = iter(val_texts)
        train_iter = itertools.chain(head, itertools.islice(texts, a.docs - len(head)))

    os.makedirs(out, exist_ok=True)
    tok.save(os.path.join(out, "tokenizer.json"))
    print(f"tokenizer trained ({tok.get_vocab_size()} tokens) at {time.time()-t0:.0f}s", flush=True)
    meta = {"dataset": a.dataset, "vocab_size": tok.get_vocab_size(), "eos_id": 0}
    meta["val_tokens"], meta["val_docs"] = write_split(tok, val_iter, os.path.join(out, "val.bin"), t0, "val")
    meta["train_tokens"], meta["train_docs"] = write_split(tok, train_iter, os.path.join(out, "train.bin"), t0, "train")
    with open(os.path.join(out, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2)
    print(f"done in {time.time()-t0:.0f}s", meta)


if __name__ == "__main__":
    main()
