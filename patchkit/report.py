"""Collect results/<task>/*.json into results/SUMMARY.md and site/data/results.json.

    python -m patchkit.report
"""
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

ARM_ORDER = ["base", "prompt", "gate", "random", "lora"]


def load_task(d):
    arms = {}
    for f in sorted(d.glob("*.json")):
        if f.name in ("signal.json",) or f.stem.startswith("_"):
            continue
        r = json.loads(f.read_text(encoding="utf-8"))
        if "arm" in r and r.get("split", "heldout") == "heldout":
            arms[r["arm"]] = r
    sweep = defaultdict(lambda: defaultdict(list))
    for f in sorted((d / "sweep").glob("*.json")) if (d / "sweep").exists() else []:
        r = json.loads(f.read_text(encoding="utf-8"))
        meth = f.stem.split("_")[0]
        sweep[meth][r["n_practice"]].append(r)
    sig = json.loads((d / "signal.json").read_text()) if (d / "signal.json").exists() else None
    return arms, sweep, sig


def fmt(v, nd=1):
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def main():
    out, md = {}, ["# Results summary", "", "Generated by `python -m patchkit.report` from `results/<task>/*.json`.", ""]
    for d in sorted(p for p in (ROOT / "results").iterdir() if p.is_dir()):
        arms, sweep, sig = load_task(d)
        if not arms:
            continue
        any_r = next(iter(arms.values()))
        h = list(any_r["headline"].keys())
        order = sorted(arms, key=lambda a: (ARM_ORDER.index(a.split("_")[0]) if a.split("_")[0] in ARM_ORDER else 9, a))
        md += [f"## {d.name}  ({any_r['model']}, n={any_r['n']} held-out)", ""]
        md += [f"| arm | {h[0]} ↓ | {h[1]} ↑ | MMLU-200 | chat KL | entries changed | trainable | fit s |",
               "|---|---|---|---|---|---|---|---|"]
        for a in order:
            r = arms[a]
            md.append(f"| {a} | {fmt(r['headline'][h[0]])} | {fmt(r['headline'][h[1]])} | {fmt(r['guards']['mmlu200'])} "
                      f"| {fmt(r['guards']['chat_kl'], 4)} | {fmt(r['cost'].get('entries_changed'))} "
                      f"| {fmt(r['cost'].get('trainable_params'))} | {fmt(r['cost'].get('fit_seconds'))} |")
        md.append("")
        sw = {}
        for meth, by_n in sweep.items():
            rows = []
            for n in sorted(by_n):
                rs = by_n[n]
                f_ = [r["headline"][h[0]] for r in rs]
                k_ = [r["headline"][h[1]] for r in rs]
                kl = [r["guards"]["chat_kl"] for r in rs]
                rows.append(dict(n=n, seeds=len(rs), failure_mean=statistics.mean(f_), failure_min=min(f_),
                                 failure_max=max(f_), kept_mean=statistics.mean(k_), kept_min=min(k_),
                                 kept_max=max(k_), kl_mean=statistics.mean(kl)))
            sw[meth] = rows
        if sw:
            md += ["Data scaling (mean over seeds; min–max):", "", f"| method | n practice | {h[0]} | {h[1]} | KL |",
                   "|---|---|---|---|---|"]
            for meth, rows in sw.items():
                for r in rows:
                    md.append(f"| {meth} | {r['n']} | {r['failure_mean']:.1f} ({r['failure_min']:.1f}–{r['failure_max']:.1f})"
                              f" | {r['kept_mean']:.1f} ({r['kept_min']:.1f}–{r['kept_max']:.1f}) | {r['kl_mean']:.4f} |")
            md.append("")
        out[d.name] = dict(model=any_r["model"], n=any_r["n"], headline_keys=h,
                           arms={a: dict(headline=arms[a]["headline"], metrics=arms[a]["metrics"],
                                         guards=arms[a]["guards"], cost=arms[a]["cost"]) for a in order},
                           sweep=sw, signal=sig)
    (ROOT / "results" / "SUMMARY.md").write_text("\n".join(md), encoding="utf-8")
    (ROOT / "site" / "data").mkdir(parents=True, exist_ok=True)
    (ROOT / "site" / "data" / "results.json").write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
